def parse(grid, w=None, h=None):
    """Frame text -> list of rows of palette indices."""
    rows = [r for r in grid.strip("\n").split("\n")]
    if h is not None and len(rows) != h:
        raise ValueError("frame has %d rows, expected %d" % (len(rows), h))
    out = []
